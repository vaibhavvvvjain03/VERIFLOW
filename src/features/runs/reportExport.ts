import { RunRecord } from '../../../shared/types';

export function generateMarkdownReport(run: RunRecord): string {
  const lines: string[] = [
    `# Veriflow Test Execution Report`,
    ``,
    `**Run ID:** \`${run.runId}\`  `,
    `**Status:** **${run.status.toUpperCase()}**  `,
    `**Target Fixture:** \`${run.targetUrl || 'http://localhost:3000/demo-store'}\`  `,
    `**Execution Mode:** \`${run.executionMode || 'Isolated Headless Automation Context'}\`  `,
    `**Browser Instance:** \`${run.browserInstance || 'Playwright Headless Chromium'}\`  `,
    `**Created At:** ${run.createdAt}  `,
    `**Started At:** ${run.startedAt || 'N/A'}  `,
    `**Completed At:** ${run.completedAt || 'N/A'}  `,
    `**Total Duration:** ${(run.summary.durationMs / 1000).toFixed(2)}s  `,
    ``,
    `## Summary`,
    ``,
    `| Metric | Count |`,
    `| :--- | :--- |`,
    `| Total Tests | ${run.summary.total} |`,
    `| Passed | ${run.summary.passed} |`,
    `| Failed | ${run.summary.failed} |`,
    ``,
    `## Test Results`,
    ``,
    `| Test ID | Name | Tag | Status | Duration | Failure Reason |`,
    `| :--- | :--- | :--- | :--- | :--- | :--- |`,
  ];

  for (const tid of run.testIds) {
    const res = run.results[tid];
    if (!res) continue;
    const statusIcon = res.status === 'passed' ? 'PASS' : res.status === 'failed' ? 'FAIL' : 'PENDING';
    const errSummary = res.error ? res.error.replace(/\n/g, ' ').substring(0, 80) + '...' : '-';
    lines.push(`| ${res.testId} | ${res.name} | ${res.tag} | ${statusIcon} | ${res.durationMs}ms | ${errSummary} |`);
  }

  lines.push(``, `## Evidence & Assertions`, ``);

  for (const tid of run.testIds) {
    const res = run.results[tid];
    if (!res) continue;
    lines.push(`### [${res.testId}] ${res.name}`);
    lines.push(`- **Status:** ${res.status.toUpperCase()}`);
    lines.push(`- **Duration:** ${res.durationMs}ms`);
    if (res.screenshotUrl) {
      lines.push(`- **Failure Screenshot:** \`${res.screenshotUrl}\``);
    }
    if (res.error) {
      lines.push(``, `\`\`\`text`, res.error, `\`\`\``);
    }
    lines.push(``);
  }

  lines.push(`---`, `*Generated by Veriflow — Evidence Before Confidence*`);

  return lines.join('\n');
}

export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
